from tortoise.migrations import operations as ops
from tortoise.migrations.schema_editor import SqliteSchemaEditor


class AddNullableField(ops.AddField):
    """AddField whose SQLite downgrade drops the column without a table rebuild."""

    async def database_backward(self, app_label, old_state, new_state, state_editor=None):
        if isinstance(state_editor, SqliteSchemaEditor):
            model = old_state.apps.get_model(f"{app_label}.{self.model_name}")
            await state_editor._run_sql(
                state_editor.DELETE_FIELD_TEMPLATE.format(
                    table=state_editor._qualify_table_name(model._meta.db_table, model._meta.schema),
                    column=model._meta.fields_db_projection[self.name],
                )
            )
        else:
            await super().database_backward(app_label, old_state, new_state, state_editor)


